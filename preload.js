const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('cisd', {
  chooseTerminal: (id) => ipcRenderer.invoke('terminal:choose', id),
  openTerminal: (id) => ipcRenderer.invoke('terminal:open', id),
  chooseImage: () => ipcRenderer.invoke('image:choose'),
  saveFundingUrl: (id, url) => ipcRenderer.invoke('funding:url', id, url),
  openFunding: (id) => ipcRenderer.invoke('funding:open', id),
  getFundingAccess: (id) => ipcRenderer.invoke('funding:access:get', id),
  saveFundingAccess: (id, payload) => ipcRenderer.invoke('funding:access:save', id, payload),
  syncFundingAccess: (id) => ipcRenderer.invoke('funding:access:sync', id),
  openGuide: () => ipcRenderer.invoke('help:open-guide'),
  resetOnboarding: () => ipcRenderer.invoke('onboarding:reset'),
  updateSettings: (patch) => ipcRenderer.invoke('settings:update', patch),
  completeOnboarding: () => ipcRenderer.invoke('onboarding:complete'),
  newsStatus: () => ipcRenderer.invoke('news:status'),
  saveNewsProvider: (provider) => ipcRenderer.invoke('news:provider', provider),
  saveNewsKey: (key) => ipcRenderer.invoke('news:key', key),
  fetchNews: () => ipcRenderer.invoke('news:fetch'),
  restore: () => ipcRenderer.invoke('data:restore'),
  exportTrades: (id) => ipcRenderer.invoke('trades:export', id),
  backup: () => ipcRenderer.invoke('data:backup'),
  resetAccount: (id) => ipcRenderer.invoke('account:reset', id),
  state: () => ipcRenderer.invoke('state:get'),
  runtimeReadiness: () => ipcRenderer.invoke('runtime:readiness'),
  dashboardSnapshot: (accountId, options) => ipcRenderer.invoke('dashboard:snapshot', accountId, options),
  analyticsSnapshot: (accountId, options) => ipcRenderer.invoke('analytics:snapshot', accountId, options),
  edgeSnapshot: (accountId, options) => ipcRenderer.invoke('edge:snapshot', accountId, options),
  playbooksOverview: (accountId, options) => ipcRenderer.invoke('playbooks:overview', accountId, options),
  savePlaybook: (payload) => ipcRenderer.invoke('playbook:save', payload),
  archivePlaybook: (id) => ipcRenderer.invoke('playbook:archive', id),
  deletePlaybook: (id) => ipcRenderer.invoke('playbook:delete', id),
  archiveAccount: (id) => ipcRenderer.invoke('account:archive', id),
  saveAccount: (account) => ipcRenderer.invoke('account:save', account),
  startBacktest: (backtest) => ipcRenderer.invoke('backtest:start', backtest),
  archiveBacktest: (id) => ipcRenderer.invoke('backtest:archive', id),
  resetBacktest: (id) => ipcRenderer.invoke('backtest:reset', id),
  stopBacktest: () => ipcRenderer.invoke('backtest:stop'),
  refreshBacktest: (id) => ipcRenderer.invoke('backtest:refresh', id),
  reviewBacktestSignal: (signalId, payload) => ipcRenderer.invoke('backtest:review-signal', signalId, payload),
  saveDaily: (day, payload) => ipcRenderer.invoke('daily:save', day, payload),
  addTrade: (trade) => ipcRenderer.invoke('trade:add', trade),
  importMT5: (id) => ipcRenderer.invoke('mt5:choose', id),
  watchFundedNext: (id) => ipcRenderer.invoke('fundednext:folder', id),
  importFundedNext: (id) => ipcRenderer.invoke('fundednext:choose', id),
  chooseCSV: () => ipcRenderer.invoke('csv:choose'),
  signalResult: (id, resultR) => ipcRenderer.invoke('signal:result', id, resultR),
  signalStatus: (id, accountId, status, reason) => ipcRenderer.invoke('signal:status', id, accountId, status, reason),
  getLocale: () => ipcRenderer.invoke('locale:get'),
  setLocale: (locale) => ipcRenderer.invoke('locale:set', locale),
  localeBundle: () => ipcRenderer.invoke('locale:bundle'),
  onChange: (handler) => ipcRenderer.on('state:changed', (_, state) => handler(state)),
  minimize: () => ipcRenderer.send('window:minimize'),
  maximize: () => ipcRenderer.send('window:maximize'),
  close: () => ipcRenderer.send('window:close'),
});
